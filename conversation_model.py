def get_user_profile(user_id, profiles_df):
    user_row = profiles_df[profiles_df["user_id"] == user_id]

    if user_row.empty:
        return "No profile available."

    profile = user_row.iloc[0].to_dict()

    profile_text = "\n".join([
        f"{key}: {value}"
        for key, value in profile.items()
        if pd.notna(value)
    ])

    return profile_text

# ============================================================
# 5. STATUS STRATEGY
# ============================================================

def create_prompt_strategy(status):
    if status == "ready_for_event":
        return "Gently suggest moving toward an event invite."

    if status == "healthy":
        return "Keep the conversation warm and flowing."

    if status == "one_sided":
        return "Change the tone, make it more interesting"

    if status == "shallow":
        return "Ask a simple but more meaningful question."

    if status == "stalled":
        return "Send a soft, low-pressure re-opening message."

    return "Continue naturally."

# ============================================================
# 6. GROQ RECOMMENDATION GENERATOR
# ============================================================

def generate_recommendation_with_profiles(
    conversation_text,
    engagement_score,
    status,
    sender_profile,
    receiver_profile
):
    strategy = create_prompt_strategy(status)

    prompt = f"""
You are helping a user continue a conversation on Sangha, a spiritual community app.

Conversation:
{conversation_text}

Engagement Score:
{engagement_score}

Conversation Status:
{status}

Strategy:
{strategy}

Sender Profile:
{sender_profile}

Receiver Profile:
{receiver_profile}

Task:
Write a recommendation and one suggested message the sender can send.

Use the profiles to make the message feel relevant, but do not be creepy.
Do not directly mention private profile details unless they naturally fit.
Do not over-personalize.

Return output in this exact format:

Recommendation:
...

Suggested Message:
...

Rules:
- Warm
- Human
- Casual
- Not salesy
- Not intense
- Make it short and action oriented
"""

    response = llm.invoke([
        SystemMessage(
            content="You write emotionally intelligent conversation recommendations for a spiritual community app."
        ),
        HumanMessage(content=prompt)
    ])

    return response.content

