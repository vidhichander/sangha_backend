# 10. Classification rules

def classify_conversation(row, score):
    msg_a = row["message_count_a"]
    msg_b = row["message_count_b"]

    if row["last_response_hours_ago"] >= 24:
        return "stalled"

    imbalance_ratio = max(msg_a, msg_b) / max(1, min(msg_a, msg_b))

    if imbalance_ratio >= 3:
        return "one_sided"

    if (
        row["avg_message_length"] < 10 and
        row["avg_response_times_minutes"] > 1000
    ):
        return "shallow"

    if score >= 90 and row["conversation_days"] >= 5:
        return "ready_for_event"

    if (65 <= score < 90) or (score >= 90 and row["conversation_days"] < 5):
        return "healthy"

    return "shallow"

# 11. Analyze any raw conversation

def analyze_raw_conversation(
    conversation_text,
    avg_response_times_minutes,
    message_count_a,
    message_count_b,
    conversation_days,
    avg_message_length,
    last_response_hours_ago
):
    total_messages = message_count_a + message_count_b
    message_gap = abs(message_count_a - message_count_b)

    message_balance_ratio = (
        min(message_count_a, message_count_b) / max(message_count_a, message_count_b)
        if max(message_count_a, message_count_b) > 0
        else 0
    )

    raw_row = {
        "conversation_text": conversation_text,
        "avg_response_times_minutes": avg_response_times_minutes,
        "message_count_a": message_count_a,
        "message_count_b": message_count_b,
        "conversation_days": conversation_days,
        "avg_message_length": avg_message_length,
        "last_response_hours_ago": last_response_hours_ago,
        "total_messages": total_messages,
        "message_gap": message_gap,
        "message_balance_ratio": message_balance_ratio
    }

    row_df = pd.DataFrame([raw_row])

    score = model.predict(row_df[[TEXT_COL] + numeric_features])[0]
    score = round(float(score), 2)

    status = classify_conversation(raw_row, score)

    return {
        "engagement_score": score,
        "status": status
    }

