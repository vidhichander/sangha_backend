# 7. Build ML pipeline

preprocessor = ColumnTransformer(
    transformers=[
        (
            "text",
            TfidfVectorizer(
                max_features=1500,
                ngram_range=(1, 2),
                stop_words="english"
            ),
            TEXT_COL
        ),
        (
            "num",
            StandardScaler(),
            numeric_features
        )
    ]
)

model = Pipeline(
    steps=[
        ("preprocessor", preprocessor),
        ("regressor", RandomForestRegressor(
            n_estimators=300,
            max_depth=10,
            min_samples_split=4,
            random_state=42
        ))
    ]
)

