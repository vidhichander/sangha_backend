def on_recommendation_button_click(
    conversation_text,
    avg_response_times_minutes,
    message_count_a,
    message_count_b,
    conversation_days,
    avg_message_length,
    last_response_hours_ago,
    sender_user_id,
    receiver_user_id
):
    # Step 1: Use ML model from Part 1
    result = analyze_raw_conversation(
        conversation_text=conversation_text,
        avg_response_times_minutes=avg_response_times_minutes,
        message_count_a=message_count_a,
        message_count_b=message_count_b,
        conversation_days=conversation_days,
        avg_message_length=avg_message_length,
        last_response_hours_ago=last_response_hours_ago
    )

    engagement_score = result["engagement_score"]
    status = result["status"]

    # Step 2: Get profiles
    sender_profile = get_user_profile(sender_user_id, profiles_df)
    receiver_profile = get_user_profile(receiver_user_id, profiles_df)

    # Step 3: Generate Groq recommendation
    llm_output = generate_recommendation_with_profiles(
        conversation_text=conversation_text,
        engagement_score=engagement_score,
        status=status,
        sender_profile=sender_profile,
        receiver_profile=receiver_profile
    )

    return {
        "engagement_score": engagement_score,
        "status": status,
        "llm_recommendation": llm_output
    }

